class Command(BaseCommand):
    help = 'Дописывает недостающие статьи и создаёт подборки для передачи знаний; повторный запуск ничего не дублирует'

    @transaction.atomic
    def handle(self, *args, **options):
        owner = User.objects.filter(is_superuser=True).order_by('pk').first()
        for data in ARTICLES:
            if Article.objects.filter(title=data['title']).exists():
                self.stdout.write(f'Статья уже есть: {data["title"]}')
                continue
            fields = {k: v for k, v in data.items() if k != 'section'}
            Article.objects.create(**fields, section=Section.objects.filter(name=data['section']).first(),
                                   author=owner, responsible=owner, status='published')
            self.stdout.write(f'Добавлена статья «{data["title"]}»')
        for title, role, project, description, entries in COLLECTIONS:
            collection, created = Collection.objects.get_or_create(title=title, defaults={
                'description': description, 'role': role, 'project': project, 'owner': owner})
            if not created:
                self.stdout.write(f'Подборка уже есть: {title}')
                continue
            position = 0
            for article_title, note in entries:
                article = Article.objects.filter(title=article_title, status='published').first()
                if article is None:
                    self.stdout.write(f'  не найдена статья: {article_title}')
                    continue
                position += 1
                CollectionItem.objects.create(collection=collection, article=article, position=position, note=note)
            self.stdout.write(f'Создана подборка «{title}», статей: {position}')
